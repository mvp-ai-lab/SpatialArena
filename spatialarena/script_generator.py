"""Renders the standalone, re-runnable scripts `BenchmarkEvaluator.evaluate()`
writes to `<experiment_root>/<experiment_name>/scripts/` before submitting
anything -- see "Generated Scripts" in the API reference (docs/benchmark/evaluator_quickstart.md).

The actual case-dispatch logic (`run_method_case_list.sh` and its two
phase-specific SLURM wrappers) is not reimplemented here: it's copied
byte-for-byte from `spatialarena/templates/_engine/` (itself a verbatim
snapshot of the hardened repo scripts) into each run's own `scripts/_engine/`
directory. This module only generates the case-list `.txt` files and the
small per-work-item wrapper scripts that call the copied engine with
concrete, resolved arguments.
"""

from __future__ import annotations

import stat
from dataclasses import dataclass
from pathlib import Path

from spatialarena.paths import SPATIALARENA_ROOT
from spatialarena.report_layout import canonical_report_dir
from spatialarena.task_track_matrix import track_runs_on_case

TEMPLATES_DIR = Path(__file__).resolve().parent / "templates"
ENGINE_DIR = TEMPLATES_DIR / "_engine"
ENGINE_FILES = (
    "run_method_case_list.sh",
    "run_method_benchmark_infer.sh",
    "run_method_benchmark_eval.sh",
)

_WRAPPER_TEMPLATE = """#!/bin/bash
{sbatch_header}# Generated by BenchmarkEvaluator -- do not hand-edit; rerun evaluate() to regenerate.
# {phase_label} phase for: {method} / {suite} / {track}
# Self-contained: submittable directly (`sbatch` picks up the #SBATCH lines
# above, copied from the engine script this wraps) or runnable directly
# (`bash`) for a native rerun. All arguments are pre-resolved below.
set -euo pipefail
# The data root this script was generated with (spatialarena/paths.py): `sbatch --export=NIL` starts the job without
# the submitting shell's environment, so defaults resolved inside the job use the same root.
export SPATIALARENA_ROOT="${{SPATIALARENA_ROOT:-{spatialarena_root}}}"
{extra_env}exec "{engine_script}" \\
    "{method}" "{suite}" "{track}" "{run_id}" "{benchmark_eval_root}" "{checkpoint_root}" \\
    "{method_code_root}" "{benchmark_aux_root}" "{exp_root}" "{report_dir}" "{exp_name}" \\
    "{keep_predictions}" "{keep_depth_visualizations}" "{generate_pdf_report}" "{case_file}"
"""


def _render_extra_env(extra_env: dict[str, str] | None) -> str:
    """Render `export VAR="value"` lines for a custom-adapter run -- e.g.
    METHOD_COMMAND (see run_method_case_list.sh's custom-method fallback
    branch) or a literal code/ckpt path override. Quoted via shlex so
    values containing spaces or shell metacharacters round-trip safely."""
    if not extra_env:
        return ""
    import shlex

    lines = [f"export {key}={shlex.quote(str(value))}" for key, value in extra_env.items()]
    return "\n".join(lines) + "\n"


def _extract_sbatch_header(engine_script: Path, *, job_name: str | None = None, log_dir: Path | None = None,
                           exclude: str | None = None, resources: dict[str, str] | None = None) -> str:
    """Pull the #SBATCH lines out of a copied engine script so the generated
    wrapper is itself directly `sbatch`-able with the right resource
    request, without duplicating those values by hand here.

    The engine's own name and log lines are generic (one log folder for every run); a wrapper replaces them with
    its run's ``job_name`` and logs under ``log_dir`` (the experiment folder), and adds ``--exclude`` when given.
    ``resources`` replaces (or adds) options by name, e.g. ``{"mem": "64G", "cpus-per-task": "8"}``."""
    resources = {f"--{key.lstrip('-')}": str(value) for key, value in (resources or {}).items()}
    lines = []
    for line in engine_script.read_text(encoding="utf-8").splitlines():
        if line.startswith("#SBATCH"):
            option = line.split()[1].split("=")[0] if len(line.split()) > 1 else ""
            if job_name and option == "--job-name":
                line = f"#SBATCH --job-name={job_name}"
            elif log_dir and option in ("--output", "--error"):
                line = f"#SBATCH {option}={log_dir}/%x_%j.{'log' if option == '--output' else 'err'}"
            elif option in resources:
                line = f"#SBATCH {option}={resources.pop(option)}"
            lines.append(line)
        elif lines:
            break  # header block ends at the first non-#SBATCH line after it starts
    if lines:
        lines.extend(f"#SBATCH {option}={value}" for option, value in resources.items())
    if lines and exclude:
        lines.append(f"#SBATCH --exclude={exclude}")
    return ("\n".join(lines) + "\n") if lines else ""


@dataclass(frozen=True)
class GeneratedCaseListEntry:
    task: str
    dataset: str
    scene: str
    interval: int = 1
    order: str | None = None


@dataclass(frozen=True)
class GeneratedRunScripts:
    work_item: dict
    case_file: Path
    infer_script: Path
    eval_script: Path
    report_dir: Path
    exp_name: str


def render_case_file(entries: list[GeneratedCaseListEntry]) -> str:
    lines = [
        "# Generated by BenchmarkEvaluator",
        "# Format: task|dataset|scene|interval|order",
    ]
    for entry in entries:
        parts = [entry.task, entry.dataset, entry.scene, str(entry.interval)]
        if entry.order:
            parts.append(entry.order)
        lines.append("|".join(parts))
    return "\n".join(lines) + "\n"


def write_case_file(path: Path, entries: list[GeneratedCaseListEntry]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_case_file(entries), encoding="utf-8")


def ensure_engine_copied(scripts_root: Path) -> Path:
    """Copy the engine scripts into `scripts_root/_engine/` if not already
    present there with matching content. Idempotent across multiple work
    items in the same run -- only copies once per experiment."""
    engine_dir = scripts_root / "_engine"
    engine_dir.mkdir(parents=True, exist_ok=True)
    for name in ENGINE_FILES:
        source = ENGINE_DIR / name
        dest = engine_dir / name
        source_bytes = source.read_bytes()
        if not dest.exists() or dest.read_bytes() != source_bytes:
            dest.write_bytes(source_bytes)
        dest.chmod(dest.stat().st_mode | stat.S_IEXEC | stat.S_IRUSR | stat.S_IRGRP)
    return engine_dir


def _method_id(method: str, track: str, env: dict | None = None) -> str:
    """``<method>_<track>`` (the method alone for ``rgb``), as run_method_case_list.sh names METHOD_ID.

    A masked-depth run with a non-default mask setting in its ``env`` carries it in the method name
    (``PI3_X-mask0.7_rgb_masked_depth``, spatialarena/depth_prior_masking.py), so it has its own report folder."""
    from spatialarena.depth_prior_masking import method_variant  # pylint: disable=import-outside-toplevel

    if track == "rgb":
        return method
    variant = method_variant(track, {str(k): str(v) for k, v in (env or {}).items()})
    return f"{method}{variant}_{track}"


def run_label(work_item: dict) -> str:
    """One work item's file-name stem: method id, suite (with the SLAM range), task and dataset.

    Every work item gets its own case file and wrappers; the engine also names the run's summary / case_failures
    TSVs after the case file, so runs sharing a method's report folder never overwrite each other's files."""
    suite = work_item["suite"]
    suite_label = f"{suite}-{work_item.get('slam_range', 'short')}" if suite == "full-slam" else suite
    method_id = _method_id(work_item["model"], work_item.get("track", "rgb"), work_item.get("env"))
    return f"{method_id}_{suite_label}_{work_item['task']}_{work_item['dataset']}"


def generate_run_scripts(
    work_item: dict,
    entries: list[GeneratedCaseListEntry],
    *,
    output_root: Path,
    run_id: str,
    benchmark_eval_root: Path,
    checkpoint_root: Path,
    method_code_root: Path,
    benchmark_aux_root: Path,
    keep_predictions: bool = True,
    keep_depth_visualizations: bool = True,
    generate_pdf_report: bool = False,
    extra_env: dict[str, str] | None = None,
    log_dir: Path | None = None,
    slurm_exclude: str | None = None,
    slurm_resources: dict[str, dict[str, str]] | None = None,
) -> GeneratedRunScripts:
    """Write one work item's case file + infer/eval wrapper scripts into
    `output_root/scripts/`. Copies the engine scripts (once per output_root)
    if not already present.

    `extra_env` renders as `export VAR=value` lines before the engine
    invocation -- used for a custom-adapter work item (METHOD_COMMAND, a
    literal code/ckpt path override; see BenchmarkEvaluator._generate_for_
    work_item and run_method_case_list.sh's custom-method fallback branch).

    `log_dir` (default `output_root/logs`) receives the jobs' SLURM logs; `slurm_exclude` is a node list for
    `#SBATCH --exclude`; `slurm_resources` overrides the engine's resource lines per phase,
    e.g. `{"eval": {"mem": "64G"}}`."""
    method = work_item["model"]
    suite = work_item["suite"]
    track = work_item.get("track", "rgb")  # select_runs() does not require a track; rgb is the default elsewhere
    method_id = _method_id(method, track, work_item.get("env"))
    # full-slam runs one range track per experiment, so the range is part of the name (as in run_method_case_list.sh).
    suite_label = f"{suite}-{work_item.get('slam_range', 'short')}" if suite == "full-slam" else suite
    exp_name = f"benchmark_{suite_label}_{method_id}"

    scripts_dir = output_root / "scripts"
    cases_dir = scripts_dir / "cases"
    engine_dir = ensure_engine_copied(scripts_dir)

    # Only the cases the track runs on (task_track_matrix: e.g. no SLAM rgb_depth on a sequence without depth maps).
    entries = [entry for entry in entries if track_runs_on_case(entry.task, track, entry.dataset, entry.scene)]
    label = run_label(work_item)
    case_file = cases_dir / f"{label}.txt"
    log_dir = log_dir if log_dir is not None else output_root / "logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    write_case_file(case_file, entries)

    # The suite's one report folder per method, shared by every run (see spatialarena/report_layout.py).
    report_dir = canonical_report_dir(benchmark_eval_root, suite, method_id, work_item.get("slam_range", "short"))

    common = {
        "method": method,
        "suite": suite,
        "track": track,
        "run_id": run_id,
        "benchmark_eval_root": benchmark_eval_root,
        "checkpoint_root": checkpoint_root,
        "method_code_root": method_code_root,
        "benchmark_aux_root": benchmark_aux_root,
        # Full suites run in the canonical artifact tree (run_method_benchmark_{infer,eval}.sh pin it there).
        "exp_root": benchmark_eval_root / "artifacts" / "full_standard",
        "report_dir": report_dir,
        "exp_name": exp_name,
        "keep_predictions": 1 if keep_predictions else 0,
        "keep_depth_visualizations": 1 if keep_depth_visualizations else 0,
        "generate_pdf_report": 1 if generate_pdf_report else 0,
        "case_file": case_file,
        "spatialarena_root": SPATIALARENA_ROOT,
    }

    extra_env_block = _render_extra_env(extra_env)

    infer_engine = engine_dir / "run_method_benchmark_infer.sh"
    infer_script = scripts_dir / f"run_{label}_infer.sh"
    infer_script.write_text(
        _WRAPPER_TEMPLATE.format(
            sbatch_header=_extract_sbatch_header(infer_engine, job_name=f"infer-{label}", log_dir=log_dir,
                                                 exclude=slurm_exclude,
                                                 resources=(slurm_resources or {}).get("infer")),
            phase_label="Inference",
            engine_script=infer_engine,
            extra_env=extra_env_block,
            **common,
        ),
        encoding="utf-8",
    )
    infer_script.chmod(infer_script.stat().st_mode | stat.S_IEXEC)

    eval_engine = engine_dir / "run_method_benchmark_eval.sh"
    eval_script = scripts_dir / f"run_{label}_eval.sh"
    eval_script.write_text(
        _WRAPPER_TEMPLATE.format(
            sbatch_header=_extract_sbatch_header(eval_engine, job_name=f"eval-{label}", log_dir=log_dir,
                                                 exclude=slurm_exclude,
                                                 resources=(slurm_resources or {}).get("eval")),
            phase_label="Evaluation",
            engine_script=eval_engine,
            extra_env=extra_env_block,
            **common,
        ),
        encoding="utf-8",
    )
    eval_script.chmod(eval_script.stat().st_mode | stat.S_IEXEC)

    return GeneratedRunScripts(
        work_item=work_item,
        case_file=case_file,
        infer_script=infer_script,
        eval_script=eval_script,
        report_dir=report_dir,
        exp_name=exp_name,
    )
