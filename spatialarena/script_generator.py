"""Renders the standalone, re-runnable job scripts of an evaluation.

`BenchmarkEvaluator.evaluate()` writes them to
`<experiment_root>/<experiment_name>/scripts/` before submitting anything;
see "Generated Scripts" in the API reference
(docs/benchmark/evaluator_quickstart.md).

The actual case-dispatch logic (`run_method_case_list.sh` and its two
phase-specific SLURM wrappers) is not reimplemented here: it is copied
byte-for-byte from `spatialarena/templates/_engine/` (itself a verbatim
snapshot of the hardened repo scripts) into each run's own `scripts/_engine/`
directory. This module only generates the case-list `.txt` files and the
small per-work-item wrapper scripts that call the copied engine with
concrete, resolved arguments.
"""

from __future__ import annotations

import dataclasses
import pathlib
import shlex
import stat

from spatialarena import paths
from spatialarena import report_layout
from spatialarena import task_track_matrix

TEMPLATES_DIR = pathlib.Path(__file__).resolve().parent / "templates"
ENGINE_DIR = TEMPLATES_DIR / "_engine"
ENGINE_FILES = (
    "run_method_case_list.sh",
    "run_method_benchmark_infer.sh",
    "run_method_benchmark_eval.sh",
)

# The wrapper script, verbatim: its lines are the generated file's lines.
_WRAPPER_TEMPLATE = """#!/bin/bash
{sbatch_header}# Generated by BenchmarkEvaluator -- do not hand-edit; rerun evaluate() to regenerate.
# {phase_label} phase for: {method} / {suite} / {track}
# Self-contained: submittable directly (`sbatch` picks up the #SBATCH lines
# above, copied from the engine script this wraps) or runnable directly
# (`bash`) for a native rerun. All arguments are pre-resolved below.
set -euo pipefail
# The data root this script was generated with (spatialarena/paths.py): `sbatch --export=NIL` starts the job without
# the submitting shell's environment, so defaults resolved inside the job use the same root.
export SPATIALARENA_ROOT="${{SPATIALARENA_ROOT:-{spatialarena_root}}}"
{extra_env}exec "{engine_script}" \\
    "{method}" "{suite}" "{track}" "{run_id}" "{benchmark_eval_root}" "{checkpoint_root}" \\
    "{method_code_root}" "{benchmark_aux_root}" "{exp_root}" "{report_dir}" "{exp_name}" \\
    "{keep_predictions}" "{keep_depth_visualizations}" "{generate_pdf_report}" "{case_file}"
"""


def _render_extra_env(extra_env: dict[str, str] | None) -> str:
    """Renders `export VAR="value"` lines for a custom-adapter run.

    For example METHOD_COMMAND (see run_method_case_list.sh's custom-method
    fallback branch) or a literal code/ckpt path override. Values are quoted
    via shlex so values containing spaces or shell metacharacters round-trip
    safely.
    """
    if not extra_env:
        return ""
    lines = [
        f"export {key}={shlex.quote(str(value))}"
        for key, value in extra_env.items()
    ]
    return "\n".join(lines) + "\n"


def _sbatch_option(line: str) -> str:
    """Returns the option name of an #SBATCH line, e.g. `--mem`."""
    words = line.split()
    if len(words) > 1:
        return words[1].split("=")[0]
    return ""


def _extract_sbatch_header(engine_script: pathlib.Path,
                           *,
                           job_name: str | None = None,
                           log_dir: pathlib.Path | None = None,
                           exclude: str | None = None,
                           resources: dict[str, str] | None = None) -> str:
    """Returns the #SBATCH lines of a copied engine script, adapted to a run.

    The generated wrapper is so itself directly `sbatch`-able with the right
    resource request, without duplicating those values by hand here.

    Args:
        engine_script: The engine script.
        job_name: Replaces the engine's generic job name.
        log_dir: Replaces the engine's log folder (one for every run) by the
            experiment folder's.
        exclude: Node list added as `--exclude`.
        resources: Options replaced (or added) by name, e.g.
            `{"mem": "64G", "cpus-per-task": "8"}`.

    Returns:
        The header lines, newline-terminated, or "" if the script has none.
    """
    resources = {
        f"--{key.lstrip('-')}": str(value)
        for key, value in (resources or {}).items()
    }
    lines = []
    for line in engine_script.read_text(encoding="utf-8").splitlines():
        if line.startswith("#SBATCH"):
            option = _sbatch_option(line)
            if job_name and option == "--job-name":
                line = f"#SBATCH --job-name={job_name}"
            elif log_dir and option in ("--output", "--error"):
                if option == "--output":
                    extension = "log"
                else:
                    extension = "err"
                line = f"#SBATCH {option}={log_dir}/%x_%j.{extension}"
            elif option in resources:
                line = f"#SBATCH {option}={resources.pop(option)}"
            lines.append(line)
        elif lines:
            # The header block ends at the first non-#SBATCH line after it
            # starts.
            break
    if lines:
        lines.extend(
            f"#SBATCH {option}={value}" for option, value in resources.items())
    if lines and exclude:
        lines.append(f"#SBATCH --exclude={exclude}")
    if not lines:
        return ""
    return "\n".join(lines) + "\n"


@dataclasses.dataclass(frozen=True)
class GeneratedCaseListEntry:
    """One line of a generated case file.

    Attributes:
        task: Benchmark task.
        dataset: Dataset name.
        scene: Scene name.
        interval: Frame interval.
        order: Optional frame order.
    """

    task: str
    dataset: str
    scene: str
    interval: int = 1
    order: str | None = None


@dataclasses.dataclass(frozen=True)
class GeneratedRunScripts:
    """The files generated for one work item.

    Attributes:
        work_item: The planned run.
        case_file: Its case list.
        infer_script: The inference wrapper script.
        eval_script: The evaluation wrapper script.
        report_dir: The report folder the engine writes to.
        exp_name: The engine's experiment name.
    """

    work_item: dict
    case_file: pathlib.Path
    infer_script: pathlib.Path
    eval_script: pathlib.Path
    report_dir: pathlib.Path
    exp_name: str


def render_case_file(entries: list[GeneratedCaseListEntry]) -> str:
    """Returns the case file text: a header, then one line per entry."""
    lines = [
        "# Generated by BenchmarkEvaluator",
        "# Format: task|dataset|scene|interval|order",
    ]
    for entry in entries:
        parts = [entry.task, entry.dataset, entry.scene, str(entry.interval)]
        if entry.order:
            parts.append(entry.order)
        lines.append("|".join(parts))
    return "\n".join(lines) + "\n"


def write_case_file(path: pathlib.Path,
                    entries: list[GeneratedCaseListEntry]) -> None:
    """Writes a case file, creating its folder."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_case_file(entries), encoding="utf-8")


def ensure_engine_copied(scripts_root: pathlib.Path) -> pathlib.Path:
    """Copies the engine scripts into `scripts_root/_engine/`.

    A script is only copied when it is missing there or its content differs,
    so this is idempotent across the work items of one run: it copies once
    per experiment.

    Args:
        scripts_root: The run's scripts folder.

    Returns:
        The engine folder.
    """
    engine_dir = scripts_root / "_engine"
    engine_dir.mkdir(parents=True, exist_ok=True)
    for name in ENGINE_FILES:
        source = ENGINE_DIR / name
        dest = engine_dir / name
        source_bytes = source.read_bytes()
        if not dest.exists() or dest.read_bytes() != source_bytes:
            dest.write_bytes(source_bytes)
        dest.chmod(dest.stat().st_mode | stat.S_IEXEC | stat.S_IRUSR |
                   stat.S_IRGRP)
    return engine_dir


def _method_id(method: str, track: str, env: dict | None = None) -> str:
    """Returns the METHOD_ID of run_method_case_list.sh.

    That is `<method>_<track>`, or the method alone for `rgb`. A masked-depth
    run with a non-default mask setting in its `env` carries it in the method
    name (`PI3_X-mask0.7_rgb_masked_depth`,
    spatialarena/depth_prior_masking.py), so it has its own report folder.
    """
    # pylint: disable-next=import-outside-toplevel
    from spatialarena import depth_prior_masking

    if track == "rgb":
        return method
    env_strings = {str(key): str(value) for key, value in (env or {}).items()}
    variant = depth_prior_masking.method_variant(track, env_strings)
    return f"{method}{variant}_{track}"


def _suite_label(work_item: dict) -> str:
    """Returns the suite, with the SLAM range for `full-slam`."""
    suite = work_item["suite"]
    if suite == "full-slam":
        return f"{suite}-{work_item.get('slam_range', 'short')}"
    return suite


def run_label(work_item: dict) -> str:
    """Returns one work item's file-name stem.

    The stem is the method id, the suite (with the SLAM range), the task and
    the dataset. Every work item gets its own case file and wrappers; the
    engine also names the run's summary / case_failures TSVs after the case
    file, so runs sharing a method's report folder never overwrite each
    other's files.

    Args:
        work_item: The planned run.

    Returns:
        The stem.
    """
    suite_label = _suite_label(work_item)
    method_id = _method_id(work_item["model"], work_item.get("track", "rgb"),
                           work_item.get("env"))
    return (f"{method_id}_{suite_label}_{work_item['task']}_"
            f"{work_item['dataset']}")


def _write_wrapper(script: pathlib.Path, engine: pathlib.Path, *,
                   sbatch_header: str, phase_label: str, extra_env: str,
                   common: dict) -> None:
    """Writes one executable wrapper script from `_WRAPPER_TEMPLATE`."""
    script.write_text(
        _WRAPPER_TEMPLATE.format(
            sbatch_header=sbatch_header,
            phase_label=phase_label,
            engine_script=engine,
            extra_env=extra_env,
            **common,
        ),
        encoding="utf-8",
    )
    script.chmod(script.stat().st_mode | stat.S_IEXEC)


def generate_run_scripts(
    work_item: dict,
    entries: list[GeneratedCaseListEntry],
    *,
    output_root: pathlib.Path,
    run_id: str,
    benchmark_eval_root: pathlib.Path,
    checkpoint_root: pathlib.Path,
    method_code_root: pathlib.Path,
    benchmark_aux_root: pathlib.Path,
    keep_predictions: bool = True,
    keep_depth_visualizations: bool = True,
    generate_pdf_report: bool = False,
    extra_env: dict[str, str] | None = None,
    log_dir: pathlib.Path | None = None,
    slurm_exclude: str | None = None,
    slurm_resources: dict[str, dict[str, str]] | None = None,
) -> GeneratedRunScripts:
    """Writes one work item's case file and infer/eval wrapper scripts.

    The files go to `output_root/scripts/`; the engine scripts are copied
    there too (once per output_root) if not already present.

    Args:
        work_item: The planned run (`model`, `suite`, `task`, `dataset`,
            optional `track`, `slam_range` and `env`).
        entries: The candidate cases; only those the track runs on are
            written.
        output_root: The experiment folder.
        run_id: Id of this evaluation run.
        benchmark_eval_root: Evaluation output root.
        checkpoint_root: Checkpoint root.
        method_code_root: Method code root.
        benchmark_aux_root: Auxiliary benchmark data root.
        keep_predictions: Keep the predictions after evaluation.
        keep_depth_visualizations: Keep the depth visualizations.
        generate_pdf_report: Generate the PDF report.
        extra_env: Rendered as `export VAR=value` lines before the engine
            invocation; used for a custom-adapter work item (METHOD_COMMAND,
            a literal code/ckpt path override; see
            BenchmarkEvaluator._generate_for_work_item and
            run_method_case_list.sh's custom-method fallback branch).
        log_dir: Receives the jobs' SLURM logs; `output_root/logs` by
            default.
        slurm_exclude: Node list for `#SBATCH --exclude`.
        slurm_resources: Overrides the engine's resource lines per phase,
            e.g. `{"eval": {"mem": "64G"}}`.

    Returns:
        The generated files.
    """
    method = work_item["model"]
    suite = work_item["suite"]
    # select_runs() does not require a track; rgb is the default elsewhere.
    track = work_item.get("track", "rgb")
    method_id = _method_id(method, track, work_item.get("env"))
    # full-slam runs one range track per experiment, so the range is part of the
    # name (as in run_method_case_list.sh).
    suite_label = _suite_label(work_item)
    exp_name = f"benchmark_{suite_label}_{method_id}"

    scripts_dir = output_root / "scripts"
    cases_dir = scripts_dir / "cases"
    engine_dir = ensure_engine_copied(scripts_dir)

    # Only the cases the track runs on (task_track_matrix: e.g. no SLAM
    # rgb_depth on a sequence without depth maps).
    entries = [
        entry for entry in entries if task_track_matrix.track_runs_on_case(
            entry.task, track, entry.dataset, entry.scene)
    ]
    label = run_label(work_item)
    case_file = cases_dir / f"{label}.txt"
    if log_dir is None:
        log_dir = output_root / "logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    write_case_file(case_file, entries)

    # The suite's one report folder per method, shared by every run (see
    # spatialarena/report_layout.py).
    report_dir = report_layout.canonical_report_dir(
        benchmark_eval_root, suite, method_id,
        work_item.get("slam_range", "short"))

    common = {
        "method": method,
        "suite": suite,
        "track": track,
        "run_id": run_id,
        "benchmark_eval_root": benchmark_eval_root,
        "checkpoint_root": checkpoint_root,
        "method_code_root": method_code_root,
        "benchmark_aux_root": benchmark_aux_root,
        # Full suites run in the canonical artifact tree
        # (run_method_benchmark_{infer,eval}.sh pin it there).
        "exp_root": benchmark_eval_root / "artifacts" / "full_standard",
        "report_dir": report_dir,
        "exp_name": exp_name,
        "keep_predictions": 1 if keep_predictions else 0,
        "keep_depth_visualizations": 1 if keep_depth_visualizations else 0,
        "generate_pdf_report": 1 if generate_pdf_report else 0,
        "case_file": case_file,
        "spatialarena_root": paths.SPATIALARENA_ROOT,
    }

    extra_env_block = _render_extra_env(extra_env)
    resources = slurm_resources or {}

    infer_engine = engine_dir / "run_method_benchmark_infer.sh"
    infer_script = scripts_dir / f"run_{label}_infer.sh"
    _write_wrapper(infer_script,
                   infer_engine,
                   sbatch_header=_extract_sbatch_header(
                       infer_engine,
                       job_name=f"infer-{label}",
                       log_dir=log_dir,
                       exclude=slurm_exclude,
                       resources=resources.get("infer")),
                   phase_label="Inference",
                   extra_env=extra_env_block,
                   common=common)

    eval_engine = engine_dir / "run_method_benchmark_eval.sh"
    eval_script = scripts_dir / f"run_{label}_eval.sh"
    _write_wrapper(eval_script,
                   eval_engine,
                   sbatch_header=_extract_sbatch_header(
                       eval_engine,
                       job_name=f"eval-{label}",
                       log_dir=log_dir,
                       exclude=slurm_exclude,
                       resources=resources.get("eval")),
                   phase_label="Evaluation",
                   extra_env=extra_env_block,
                   common=common)

    return GeneratedRunScripts(
        work_item=work_item,
        case_file=case_file,
        infer_script=infer_script,
        eval_script=eval_script,
        report_dir=report_dir,
        exp_name=exp_name,
    )
